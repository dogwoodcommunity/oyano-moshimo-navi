-- Isolated runtime regression for monthly_checkin_notifications.sql.
-- Run only in a disposable PostgreSQL database. Everything is rolled back.

begin;

do $bootstrap$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then
    create role service_role nologin;
  end if;
end;
$bootstrap$;

create table public.profiles (
  id uuid primary key,
  email text
);

create table public.push_tokens (
  user_id uuid not null,
  is_active boolean default true
);

create table public.notification_preferences (
  user_id uuid not null,
  daily_digest_enabled boolean default true,
  updated_at timestamptz default now()
);

create table public.scheduled_notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  task_id uuid,
  notification_type text not null default 'due_1d',
  scheduled_for timestamptz not null,
  status text not null default 'scheduled'
);

\ir monthly_checkin_notifications.sql

-- Emulate production's old explicit grants. Revoking PUBLIC alone must not
-- count as closing anon/authenticated access after CREATE OR REPLACE.
grant execute on function public.ensure_monthly_checkin_notifications() to anon, authenticated;
\ir monthly_checkin_notifications.sql

insert into public.profiles (id, email)
